/** Кто радуется на победе — случайный член семьи с его фразой. */
export function familyLine(who) {
  const keys = Object.keys(FAMILY_MSG);
  const k = who && FAMILY_MSG[who] ? who : keys[Math.floor(Math.random() * keys.length)];
  const list = FAMILY_MSG[k];
  return { who: k, text: list[Math.floor(Math.random() * list.length)] };
}

