// Детерминированный генератор случайных чисел (xorshift32) по сиду.
// Тот же, что был в старом index.html: одинаковый сид → одинаковый уровень.
export function makeRng(seed) {
  let s = (Math.imul(seed, 2654435761) >>> 0) || 1;
  return () => {
    s = (s ^ (s << 13)) >>> 0;
    s = (s ^ (s >>> 17)) >>> 0;
    s = (s ^ (s << 5)) >>> 0;
    return s / 4294967296;
  };
}
